const dictionaries: Record<Lang, Record<MsgKey, string>> = { en, fr, de, it };

export type TFunc = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFunc {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) {
      // "{n?one|other}": singular or plural by the number n (French: 0 and 1 singular; German, Italian, English: 1)
      const n = Number(String(vars.n ?? "").replace(/[^\d.-]/g, ""));
      const one = lang === "fr" ? Math.abs(n) < 2 : n === 1;
      s = s.replace(/\{n\?([^|}]*)\|([^}]*)\}/g, (_, a: string, b: string) => (one ? a : b));
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
}

const STORAGE_KEY = "st-lang";

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (isLang(v)) return v;
  } catch {
    /* storage unavailable */
  }
  // first visit: the browser's first Swiss national language, else French (English only when picked)
  for (const l of navigator.languages ?? []) {
    const code = l.slice(0, 2).toLowerCase();
    if (code === "fr" || code === "de" || code === "it") return code;
  }
  return "fr";
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}

export interface I18n {
  lang: Lang;
  locale: string;
  t: TFunc;
  setLang: (l: Lang) => void;
}

export const I18nContext = createContext<I18n>({
  lang: "en",
  locale: "en-GB",
  t: makeT("en"),
  setLang: () => {},
});

export const useI18n = () => useContext(I18nContext);
